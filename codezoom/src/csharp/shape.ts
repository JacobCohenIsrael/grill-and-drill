// Member body shapes for Duplicates (ADR 0009). Two bodies have the same
// shape when their syntax trees match once every name and every literal is
// ignored; keywords, operators and structure must match. Nodes are counted
// and tokens written the way the probe behind ADR 0009 did, so the minimum
// of 50 syntax nodes means what was measured: every named node but comments,
// the body's own node included.

import { createHash } from "node:crypto";
import type { Shape } from "./facts.js";
import type { LiteNode } from "./lite.js";

/** Bodies with fewer syntax nodes are never Duplicates: about six lines. */
export const MIN_SHAPE_NODES = 50;

const LITERALS = new Set([
  "integer_literal",
  "real_literal",
  "string_literal",
  "verbatim_string_literal",
  "raw_string_literal",
  "character_literal",
  "boolean_literal",
  "null_literal",
  // the text between an interpolated string's holes
  "string_content",
]);

/** Named leaves that are keywords: their text is part of the shape (`int`, `var`, `static`). */
const KEYWORD_LEAVES = new Set(["predefined_type", "implicit_type", "modifier"]);

/** What generators write in a file's header comment. */
const GENERATED_HEADER =
  /<auto-?generated|auto-?generated|this (code|file) (was|is) (auto-?)?generated|generated by (a )?tool|do not (edit|modify)|\[(System\.CodeDom\.Compiler\.)?GeneratedCode|\[(System\.Runtime\.CompilerServices\.)?CompilerGenerated|changes to this file (may|will) (cause|be lost)/i;

/**
 * An auto-generated header: the pattern in the comments before the file's
 * first line of code (blank lines and `#` directives such as `#pragma` may sit
 * among them). A doc comment further down that says "do not edit" is not one.
 */
export function hasGeneratedHeader(text: string): boolean {
  return GENERATED_HEADER.test(headerComments(text));
}

/** The comments before the first line of code, joined. */
export function headerComments(text: string): string {
  const out: string[] = [];
  let i = text.charCodeAt(0) === 0xfeff ? 1 : 0;
  while (i < text.length) {
    const c = text[i];
    if (c === " " || c === "\t" || c === "\r" || c === "\n") {
      i++;
    } else if (text.startsWith("//", i) || c === "#") {
      const end = text.indexOf("\n", i);
      const stop = end < 0 ? text.length : end;
      if (c !== "#") out.push(text.slice(i + 2, stop));
      i = stop;
    } else if (text.startsWith("/*", i)) {
      const end = text.indexOf("*/", i + 2);
      const stop = end < 0 ? text.length : end + 2;
      out.push(text.slice(i + 2, end < 0 ? text.length : end));
      i = stop;
    } else {
      break;
    }
  }
  return out.join("\n");
}

/** `[GeneratedCode(...)]` on a type, by any spelling of its name. */
export function isGeneratedCodeAttribute(name: string): boolean {
  return /(^|\.)GeneratedCode(Attribute)?$/.test(name);
}

/** The shape of one body: a block or an `=> expression`. Null below the minimum. */
export function shapeOf(body: LiteNode, line: number, accessor?: string): Shape | null {
  const tokens: string[] = [];
  const nodes = write(body, tokens);
  return finish(tokens, nodes, line, accessor);
}

/** Top-level statements as one body, as if they were written in Main's block. */
export function topLevelShape(statements: LiteNode[], line: number): Shape | null {
  const tokens = ["(block", "{"];
  let nodes = 1;
  for (const s of statements) for (const c of s.children) nodes += write(c, tokens);
  tokens.push("}", ")");
  return finish(tokens, nodes, line);
}

function finish(tokens: string[], nodes: number, line: number, accessor?: string): Shape | null {
  if (nodes < MIN_SHAPE_NODES) return null;
  const hash = createHash("sha1").update(tokens.join(" ")).digest("base64");
  return accessor ? { hash, nodes, line, accessor } : { hash, nodes, line };
}

/** Writes a node's tokens; returns how many named nodes it holds, itself included. */
function write(node: LiteNode, out: string[]): number {
  const t = node.type;
  if (t === "comment") return 0;
  if (!node.isNamed) {
    out.push(t); // a keyword, operator or punctuation: its type is its text
    return 0;
  }
  if (t === "identifier") {
    out.push("$I");
    return 1;
  }
  if (LITERALS.has(t)) {
    out.push("$L");
    return 1;
  }
  if (node.childCount === 0) {
    out.push(KEYWORD_LEAVES.has(t) ? node.text : t);
    return 1;
  }
  out.push(`(${t}`);
  let n = 1;
  for (const c of node.children) n += write(c, out);
  out.push(")");
  return n;
}
